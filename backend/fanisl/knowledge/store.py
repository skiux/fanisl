    # --- 单元核查（站上意见 → 知识席位答复）与修改留痕 -----------------------

    REVIEW_CATEGORIES = ("quote", "grade", "scoring", "asset", "statement", "other")
    REVIEW_STATUSES = ("open", "answered", "closed")
    REVIEW_OUTCOMES = ("fixed", "no_change", "needs_info")
    REVIEW_BODY_MAX = 4000
    # 改了这些字段，已落库的评分就对不上单元了——评分器只认提取时冻结的 spec
    _SCORING_FIELDS = ("verifiability", "scoring_spec", "asset_symbol", "direction",
                       "magnitude", "horizon", "condition_text", "condition_observable")

    def _clean_body(self, body: str) -> str:
        body = (body or "").strip()
        if not body:
            raise ValueError("内容不能为空")
        if len(body) > self.REVIEW_BODY_MAX:
            raise ValueError(f"内容超过 {self.REVIEW_BODY_MAX} 字")
        return body

    @staticmethod
    def _lock_review(conn, review_id: int) -> dict:
        row = conn.execute("SELECT id, unit_id, status FROM unit_reviews WHERE id=%s FOR UPDATE",
                           (review_id,)).fetchone()
        if row is None:
            raise LookupError(f"核查 {review_id} 不存在")
        return row

    def create_review(self, unit_id: int, *, category: str, body: str, author: str) -> dict:
        """站上用户对一条单元提出核查意见。返回 review_detail。"""
        if category not in self.REVIEW_CATEGORIES:
            raise ValueError(f"category 须为 {'/'.join(self.REVIEW_CATEGORIES)}")
        body = self._clean_body(body)
        with self.pool.connection() as conn:
            if conn.execute("SELECT 1 FROM knowledge_units WHERE id=%s", (unit_id,)).fetchone() is None:
                raise LookupError(f"单元 {unit_id} 不存在")
            rid = conn.execute(
                "INSERT INTO unit_reviews(unit_id, category, created_by) VALUES (%s,%s,%s) RETURNING id",
                (unit_id, category, author)).fetchone()["id"]
            conn.execute("INSERT INTO unit_review_messages(review_id, role, author, body) "
                         "VALUES (%s,'reviewer',%s,%s)", (rid, author, body))
        return self.review_detail(rid)

    def add_review_message(self, review_id: int, *, body: str, author: str) -> dict:
        """站上用户在核查里补充说明、或回复知识席位的答复。已答复/已关闭的会重新打开。"""
        body = self._clean_body(body)
        with self.pool.connection() as conn:
            self._lock_review(conn, review_id)
            conn.execute("INSERT INTO unit_review_messages(review_id, role, author, body) "
                         "VALUES (%s,'reviewer',%s,%s)", (review_id, author, body))
            conn.execute("UPDATE unit_reviews SET status='open', closed_at=NULL, updated_at=now() "
                         "WHERE id=%s", (review_id,))
        return self.review_detail(review_id)

    def close_review(self, review_id: int) -> dict:
        """站上用户关闭核查（认可答复，或撤回）。之后再回复会重新打开。"""
        with self.pool.connection() as conn:
            if self._lock_review(conn, review_id)["status"] == "closed":
                raise ReviewConflict(f"核查 {review_id} 已经关闭")
            conn.execute("UPDATE unit_reviews SET status='closed', closed_at=now(), updated_at=now() "
                         "WHERE id=%s", (review_id,))
        return self.review_detail(review_id)

    def answer_review(self, review_id: int, *, body: str, outcome: str, author: str,
                      root_cause: str | None = None, sweep: str | None = None,
                      followup: str | None = None) -> dict:
        """知识席位答复一条待处理的核查。只由 CLI 调用，不开 HTTP。

        outcome=fixed 有两道闸：必须先有挂在这条核查下的修改记录（说改了就得真改了），
        root_cause 与 sweep 必须写（为什么会错、同类单元查了哪些）——否则等于只修了
        用户恰好看见的那一条。
        """
        if outcome not in self.REVIEW_OUTCOMES:
            raise ValueError(f"outcome 须为 {'/'.join(self.REVIEW_OUTCOMES)}")
        body = self._clean_body(body)
        root_cause, sweep, followup = ((x or "").strip() or None for x in (root_cause, sweep, followup))
        if outcome == "fixed" and not (root_cause and sweep):
            raise ValueError("outcome=fixed 时必须写 root_cause（为什么会错）"
                             "与 sweep（同类单元查了哪些、结果如何）")
        with self.pool.connection() as conn:
            row = self._lock_review(conn, review_id)
            if row["status"] != "open":
                raise ReviewConflict(f"核查 {review_id} 当前是 {row['status']}，只能答复 open 的")
            if outcome == "fixed" and conn.execute(
                    "SELECT 1 FROM unit_amendments WHERE review_id=%s", (review_id,)).fetchone() is None:
                raise ReviewConflict("outcome=fixed，但这条核查下没有修改记录——"
                                     "先用 amend 改单元并挂上 --review")
            conn.execute(
                "INSERT INTO unit_review_messages(review_id, role, author, body, resolution) "
                "VALUES (%s,'extractor',%s,%s,%s)",
                (review_id, author, body, Json({"outcome": outcome, "root_cause": root_cause,
                                                "sweep": sweep, "followup": followup})))
            conn.execute("UPDATE unit_reviews SET status='answered', updated_at=now() WHERE id=%s",
                         (review_id,))
        return self.review_detail(review_id)

    def review_detail(self, review_id: int) -> dict | None:
        """一条核查：本体 + 对话（按时间）+ 挂在它下面的修改记录（带改动字段清单）。"""
        with self.pool.connection() as conn:
            r = conn.execute("SELECT * FROM unit_reviews WHERE id=%s", (review_id,)).fetchone()
            if r is None:
                return None
            r["messages"] = conn.execute(
                "SELECT id, role, author, body, resolution, created_at FROM unit_review_messages "
                "WHERE review_id=%s ORDER BY id", (review_id,)).fetchall()
            r["amendments"] = conn.execute(
                "SELECT id, unit_id, before, after, reason, author, created_at FROM unit_amendments "
                "WHERE review_id=%s ORDER BY id", (review_id,)).fetchall()
        for a in r["amendments"]:
            a["changed"] = amendment_changes(a["before"], a["after"])
        return r

    def reviews_for_unit(self, unit_id: int) -> list[dict]:
        """单元详情里的核查面板：该单元的全部核查，新的在前。"""
        with self.pool.connection() as conn:
            ids = [row["id"] for row in conn.execute(
                "SELECT id FROM unit_reviews WHERE unit_id=%s ORDER BY id DESC", (unit_id,)).fetchall()]
        return [self.review_detail(i) for i in ids]

    def list_reviews(self, *, status: str | None = None, limit: int = 100) -> list[dict]:
        """核查队列：open 是知识席位的待办，answered 是用户的待确认。带单元摘要，不带对话全文。"""
        if status is not None and status not in self.REVIEW_STATUSES:
            raise ValueError(f"status 须为 {'/'.join(self.REVIEW_STATUSES)}")
        where, params = ("WHERE r.status=%s", (status,)) if status else ("", ())
        with self.pool.connection() as conn:
            return conn.execute(
                "SELECT r.*, u.kind, u.content_id, left(u.quote, 80) AS quote, "
                "u.payload->>'verifiability' AS verifiability, cr.name AS creator, "
                "(SELECT count(*) FROM unit_review_messages m WHERE m.review_id=r.id) AS n_messages, "
                "(SELECT left(m.body, 120) FROM unit_review_messages m WHERE m.review_id=r.id "
                " ORDER BY m.id DESC LIMIT 1) AS last_message "
                "FROM unit_reviews r JOIN knowledge_units u ON u.id=r.unit_id "
                f"JOIN creators cr ON cr.id=u.creator_id {where} "
                "ORDER BY r.updated_at DESC LIMIT %s", (*params, limit)).fetchall()

    def amend_unit(self, unit_id: int, *, reason: str, author: str, quote: str | None = None,
                   payload: dict | None = None, tags: list[str] | None = None,
                   review_id: int | None = None) -> dict:
        """原地修改一条单元并留痕（改前 / 改后 / 原因）。返回修改记录。

        与导入同一套闸门：pydantic 重验载荷、quote 须逐字出自原文。已有评分记录的单元
        不许改评分相关字段——历史评分会对不上单元；真要改评分语义，升 extractor_version 重提。
        """
        reason = (reason or "").strip()
        if not reason:
            raise ValueError("reason 不能为空")
        if quote is None and payload is None and tags is None:
            raise ValueError("没有要改的字段")
        with self.pool.connection() as conn:
            u = conn.execute(
                "SELECT u.kind, u.quote, u.locator, u.payload, u.tags, c.raw FROM knowledge_units u "
                "JOIN contents c ON c.id=u.content_id WHERE u.id=%s FOR UPDATE OF u", (unit_id,)).fetchone()
            if u is None:
                raise LookupError(f"单元 {unit_id} 不存在")
            if review_id is not None and conn.execute(
                    "SELECT 1 FROM unit_reviews WHERE id=%s AND unit_id=%s",
                    (review_id, unit_id)).fetchone() is None:
                raise ValueError(f"核查 {review_id} 不是针对单元 {unit_id} 的")
            new = KnowledgeUnit(kind=u["kind"], locator=u["locator"],
                                quote=u["quote"] if quote is None else quote,
                                payload=u["payload"] if payload is None else payload,
                                tags=u["tags"] if tags is None else tags)
            if not quote_in_source(u["raw"], new.quote):
                raise ValueError("quote 不在原文中（空白归一后须是子串）")
            before = {"quote": u["quote"], "payload": u["payload"], "tags": u["tags"]}
            after = {"quote": new.quote, "payload": new.payload, "tags": new.tags}
            if before == after:
                raise ValueError("改后与改前完全相同")
            # 旧载荷也过一遍模型再比，否则模型补的默认字段（如 benchmark: null）会被误判成改动
            try:
                old_payload = KnowledgeUnit(kind=u["kind"], quote=u["quote"], payload=u["payload"]).payload
            except ValueError:
                old_payload = u["payload"]
            touched = [f for f in self._SCORING_FIELDS if old_payload.get(f) != new.payload.get(f)]
            # 作废过的也算评过：否则先作废、再改判据，就成了看过结果再改答案
            if touched and conn.execute(
                    "SELECT 1 FROM claim_scores WHERE unit_id=%s "
                    "UNION ALL SELECT 1 FROM claim_score_voids WHERE unit_id=%s LIMIT 1",
                    (unit_id, unit_id)).fetchone():
                raise ReviewConflict(f"单元 {unit_id} 已有评分记录，不能改评分相关字段 {touched}；"
                                     "要改评分语义请升 extractor_version 重提")
            conn.execute("UPDATE knowledge_units SET quote=%s, payload=%s, tags=%s WHERE id=%s",
                         (new.quote, Json(new.payload), new.tags, unit_id))
            row = conn.execute(
                "INSERT INTO unit_amendments(unit_id, review_id, before, after, reason, author) "
                "VALUES (%s,%s,%s,%s,%s,%s) RETURNING *",
                (unit_id, review_id, Json(before), Json(after), reason, author)).fetchone()
        row["changed"] = amendment_changes(row["before"], row["after"])
        return row

    def void_score(self, unit_id: int, horizon_label: str, *, reason: str, author: str,
                   rescore: bool = False) -> dict:
        """作废一个评分时点：整行搬进 claim_score_voids（原样保留），从 claim_scores 移走。

        默认用于本不该存在的评分时点，作废后评分器不会再评它。`rescore=True` 用于评分器没按冻结的
        success_def 执行（机器配置漏了条件等）：配置修好后下一次运行重评。两者都不是改判据——
        判据写错要改单元并留痕，且评过分的单元评分字段是锁定的。
        """
        reason = (reason or "").strip()
        if not reason:
            raise ValueError("reason 不能为空")
        with self.pool.connection() as conn:
            rows = conn.execute(
                "SELECT * FROM claim_scores WHERE unit_id=%s AND horizon_label=%s FOR UPDATE",
                (unit_id, horizon_label)).fetchall()
            if not rows:
                raise LookupError(f"单元 {unit_id} 在 {horizon_label} 没有评分记录")
            out = None
            for r in rows:
                snapshot = {k: (v.isoformat() if hasattr(v, "isoformat") else v) for k, v in r.items()}
                out = conn.execute(
                    "INSERT INTO claim_score_voids(unit_id, horizon_label, scorer_version, score, reason, "
                    "author, rescore) VALUES (%s,%s,%s,%s,%s,%s,%s) RETURNING *",
                    (unit_id, horizon_label, r["scorer_version"], Json(snapshot), reason, author,
                     rescore)).fetchone()
                conn.execute("DELETE FROM claim_scores WHERE id=%s", (r["id"],))
        return out

    def score_voids(self, unit_id: int) -> list[dict]:
        with self.pool.connection() as conn:
            return conn.execute("SELECT * FROM claim_score_voids WHERE unit_id=%s ORDER BY id",
                                (unit_id,)).fetchall()

    def recent_scores(self, *, days: int = 14, limit: int = 100) -> list[dict]:
        """新到期评分流（今日页）：按评分落库时刻倒序，带单元与信源摘要。"""
        with self.pool.connection() as conn:
            return conn.execute(
                "SELECT s.id, s.unit_id, s.horizon_label, s.outcome, s.realized, "
                "s.eval_ts, s.created_at AS scored_at, "
                "u.kind, u.quote, u.payload, u.published_at, u.creator_id, u.content_id, "
                "cr.name AS creator, c.title AS content_title "
                f"FROM claim_scores s JOIN knowledge_units u ON u.id=s.unit_id "
                f"JOIN creators cr ON cr.id=u.creator_id JOIN contents c ON c.id=u.content_id "
                f"WHERE s.created_at >= now() - make_interval(days => %s) AND {ACTIVE_RUN} "
                f"ORDER BY s.created_at DESC, s.id DESC LIMIT %s", (days, limit),
            ).fetchall()

    def verification_queue(self, *, days: int = 14, limit: int = 120) -> dict:
        """验证中心的行动队列。

        评分行只代表已发生的判定；即将到期的 Claim 需从冻结的 eval_ladder
        反查，不能把“尚未写入评分”误报成没有工作。这是纯读取视图，不改变
        评分器或任何状态。
        """
        with self.pool.connection() as conn:
            due = conn.execute(f"""
                SELECT u.id AS unit_id, u.quote, u.payload, u.published_at,
                  u.ref_price_at_publish, cr.name AS creator, c.title AS content_title,
                  ladder.label AS horizon_label
                FROM knowledge_units u
                JOIN creators cr ON cr.id=u.creator_id
                JOIN contents c ON c.id=u.content_id
                CROSS JOIN LATERAL jsonb_array_elements_text(
                  COALESCE(u.payload->'scoring_spec'->'eval_ladder', '[]'::jsonb)
                ) AS ladder(label)
                WHERE u.kind='claim' AND {ACTIVE_RUN}
                  AND ladder.label ~ '^\\d{{4}}-\\d{{2}}-\\d{{2}}$'
                  AND ladder.label::date BETWEEN current_date AND current_date + %s
                  AND NOT EXISTS (
                    SELECT 1 FROM claim_scores s
                    WHERE s.unit_id=u.id AND s.horizon_label=ladder.label
                  )
                ORDER BY ladder.label, u.published_at DESC NULLS LAST
                LIMIT %s
            """, (days, limit)).fetchall()
            scores = conn.execute(f"""
                SELECT s.id AS score_id, s.unit_id, s.horizon_label, s.outcome, s.realized,
                  s.eval_ts, s.created_at AS scored_at, u.quote, u.payload, u.published_at,
                  u.ref_price_at_publish, cr.name AS creator, c.title AS content_title
                FROM claim_scores s
                JOIN knowledge_units u ON u.id=s.unit_id
                JOIN creators cr ON cr.id=u.creator_id
                JOIN contents c ON c.id=u.content_id
                WHERE {ACTIVE_RUN}
                ORDER BY s.created_at DESC, s.id DESC
                LIMIT %s
            """, (limit,)).fetchall()

        verdicts = [s for s in scores if s["outcome"] in {"hit", "partial", "miss"}]
        unavailable = [s for s in scores if s["outcome"] in {
            "unpriceable", "condition_unverifiable",
        }]
        review = [s for s in scores if s["outcome"] in {"condition_not_met", "pending"}]
        return {
            "overview": {
                "due": len(due), "completed": len(verdicts), "unavailable": len(unavailable),
                "review": len(review),
            },
            "due": due,
            "recent": verdicts,
            "unavailable": unavailable,
            "review": review,
        }

    def verification_detail(self, score_id: int) -> dict | None:
        """一次已落库验证的不可变判定档案，含出处和受影响的知识节点。"""
        with self.pool.connection() as conn:
            row = conn.execute("""
                SELECT s.id AS score_id, s.unit_id, s.horizon_label, s.outcome, s.realized,
                  s.eval_ts, s.created_at AS scored_at, s.scorer_version,
                  u.quote, u.locator, u.payload, u.tags, u.published_at,
                  u.ref_price_at_publish, u.extractor_version,
                  cr.id AS creator_id, cr.name AS creator,
                  c.id AS content_id, c.title AS content_title, c.url AS content_url
                FROM claim_scores s
                JOIN knowledge_units u ON u.id=s.unit_id
                JOIN creators cr ON cr.id=u.creator_id
                JOIN contents c ON c.id=u.content_id
                WHERE s.id=%s
            """, (score_id,)).fetchone()
            if row is None:
                return None
            row["nodes"] = conn.execute("""
                SELECT n.id, n.title, n.status, n.kind, a.relation, a.note
                FROM node_attestations a JOIN knowledge_nodes n ON n.id=a.node_id
                WHERE a.unit_id=%s ORDER BY n.id
            """, (row["unit_id"],)).fetchall()
        return row

    def units(self, *, kind: str | None = None, creator_id: int | None = None,
              limit: int = 100) -> list[dict]:
        cond, params = [ACTIVE_RUN], []
        if kind:
            cond.append("u.kind=%s")
            params.append(kind)
        if creator_id:
            cond.append("u.creator_id=%s")
            params.append(creator_id)
        where = "WHERE " + " AND ".join(cond)
        with self.pool.connection() as conn:
            return conn.execute(
                f"SELECT u.* FROM knowledge_units u {where} "
                f"ORDER BY u.published_at DESC NULLS LAST LIMIT %s", (*params, limit),
            ).fetchall()
