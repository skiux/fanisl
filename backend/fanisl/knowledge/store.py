# 下游统计只看当前生效那一版提取。凡是**数单元/算比例/挑待办**的查询都要带上它；
# 按 unit_id 单查、或从 claim_scores 反查（已被 unit_id 限定）的不用带。
# 别名固定为 u，用法：f"... FROM knowledge_units u WHERE ... AND {ACTIVE_RUN}"
ACTIVE_RUN = ("EXISTS (SELECT 1 FROM extraction_runs r "
              "WHERE r.id = u.run_id AND r.status = 'active')")

# 同理，重转录后的旧稿（contents.status='superseded'）不该进任何"有几期内容"的计数。
# 别名固定为 c。**去重前置闸不能带它**（upsert_content 的 dedup_hash 查询、
# content_url_exists）——那两处正需要看见旧稿，否则同一个视频会被反复付费转录。
LIVE_CONTENT = "c.status <> 'superseded'"


def dedup_hash(raw: str) -> str:
    return hashlib.sha256(raw.strip().encode()).hexdigest()[:32]


def quote_in_source(raw: str, quote: str) -> bool:
    """quote 必须逐字出自原文：空白归一后是子串。导入与单元修改共用这一条规则。"""
    return re.sub(r"\s+", "", quote) in re.sub(r"\s+", "", raw)


def amendment_changes(before: dict, after: dict) -> list[str]:
    """一次修改动了哪些字段（quote / tags / payload.<键>），供 CLI 与前端直接展示。"""
    out = [k for k in ("quote", "tags") if before.get(k) != after.get(k)]
    bp, ap = before.get("payload") or {}, after.get("payload") or {}
    return out + [f"payload.{k}" for k in sorted(set(bp) | set(ap)) if bp.get(k) != ap.get(k)]


class ReviewConflict(Exception):
    """核查或单元的当前状态不允许这个操作（例如答复一条不在 open 的核查）。API 映射 409。

    约定：输入不合法抛 ValueError（400），对象不存在抛 LookupError（404）。
    """


class KnowledgeStore:
    def __init__(self, pool: ConnectionPool) -> None:
        self.pool = pool
        with pool.connection() as conn:
            conn.execute(_SCHEMA)

    # --- 信源 -------------------------------------------------------------

    def ensure_creator(self, name: str, *, lang: str = "zh", focus: str | None = None,
                       notes: str | None = None) -> int:
        with self.pool.connection() as conn:
            row = conn.execute(
                "INSERT INTO creators(name, lang, focus, notes) VALUES (%s,%s,%s,%s) "
                "ON CONFLICT (name) DO UPDATE SET lang=EXCLUDED.lang RETURNING id",
                (name, lang, focus, notes),
            ).fetchone()
        return int(row["id"])

    def ensure_handle(self, creator_id: int, platform: str, handle: str,
                      url: str | None = None) -> int:
        with self.pool.connection() as conn:
            row = conn.execute(
                "INSERT INTO creator_handles(creator_id, platform, handle, url) "
                "VALUES (%s,%s,%s,%s) ON CONFLICT (platform, handle) DO UPDATE "
                "SET url=EXCLUDED.url RETURNING id",
                (creator_id, platform, handle, url),
            ).fetchone()
        return int(row["id"])

    def creators(self) -> list[dict]:
        with self.pool.connection() as conn:
            rows = conn.execute(
                "SELECT c.*, COALESCE(json_agg(json_build_object('platform', h.platform, "
                "'handle', h.handle, 'url', h.url)) FILTER (WHERE h.id IS NOT NULL), '[]') AS handles "
                "FROM creators c LEFT JOIN creator_handles h ON h.creator_id=c.id "
                "GROUP BY c.id ORDER BY c.id",
            ).fetchall()
        return rows

    # --- L0 内容（追加式）--------------------------------------------------

    def upsert_content(self, creator_id: int, *, platform: str, url: str | None,
                       content_type: str, title: str | None, published_at,
                       raw: str, lang: str | None = None,
                       triage: dict | None = None,
                       handle: str | None = None) -> tuple[int, bool]:
        """按 dedup_hash 幂等插入。返回 (content_id, 是否新建)。已存在时不改原文。

        triage 记转录出处（model/channel）。2026-08 的教训：lite 档模型会改写数字，
        事后想圈出受影响的内容却发现库里没留通道记录，只能靠会话日志回溯。
        handle 是摄取自哪个频道，每日摄取按它算缺口（见 daily.ingest_since_days）。
        """
        h = dedup_hash(raw)
        with self.pool.connection() as conn:
            row = conn.execute("SELECT id FROM contents WHERE dedup_hash=%s", (h,)).fetchone()
            if row:
                return int(row["id"]), False
            row = conn.execute(
                "INSERT INTO contents(creator_id, platform, url, content_type, title, "
                "published_at, lang, raw, dedup_hash, triage, handle) "
                "VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s) RETURNING id",
                (creator_id, platform, url, content_type, title, published_at, lang, raw, h,
                 Json(triage) if triage else None, handle),
            ).fetchone()
        return int(row["id"]), True

    def content_url_exists(self, url: str) -> bool:
        """按 URL 判存（批量回填跳过已转录的视频，省 Gemini 开销；raw 哈希去重之外的前置闸）。"""
        with self.pool.connection() as conn:
            return conn.execute("SELECT 1 FROM contents WHERE url=%s LIMIT 1", (url,)).fetchone() is not None

    def set_triage(self, content_id: int, triage: dict, status: str) -> None:
        with self.pool.connection() as conn:
            conn.execute("UPDATE contents SET triage=%s, status=%s WHERE id=%s",
                         (Json(triage), status, content_id))

    def set_status(self, content_id: int, status: str) -> None:
        with self.pool.connection() as conn:
            conn.execute("UPDATE contents SET status=%s WHERE id=%s", (status, content_id))

    def contents_by_status(self, status: str, *, limit: int = 50) -> list[dict]:
        with self.pool.connection() as conn:
            return conn.execute(
                "SELECT * FROM contents WHERE status=%s ORDER BY published_at NULLS LAST "
                "LIMIT %s", (status, limit),
            ).fetchall()

    def get_content(self, content_id: int) -> dict | None:
        with self.pool.connection() as conn:
            return conn.execute(
                "SELECT c.*, cr.name AS creator FROM contents c "
                "JOIN creators cr ON cr.id=c.creator_id WHERE c.id=%s", (content_id,),
            ).fetchone()

    def list_contents(self, *, status: str | None = None, limit: int = 200) -> list[dict]:
        """内容列表（不含 raw 全文，带信源名/字数/单元构成/评分摘要）——前端列表页用。

        默认排除 superseded：重转录后的旧稿是 L0 的历史记录（append-only 不删），但任何
        "这个信源有几期"的计数都不该把同一期算两遍。要看旧稿传 status='superseded'。
        """
        cond = "WHERE c.status=%s" if status else f"WHERE {LIVE_CONTENT}"
        params: tuple = (status, limit) if status else (limit,)
        with self.pool.connection() as conn:
            return conn.execute(
                f"SELECT c.id, c.creator_id, cr.name AS creator, c.platform, c.url, "
                f"c.content_type, c.title, c.published_at, c.fetched_at, c.lang, c.status, "
                f"length(c.raw) AS raw_len, "
                f"(SELECT count(*) FROM knowledge_units u WHERE u.content_id=c.id AND {ACTIVE_RUN}) AS n_units, "
                f"(SELECT count(*) FROM knowledge_units u WHERE u.content_id=c.id AND u.kind='claim' AND {ACTIVE_RUN}) AS n_claims, "
                f"(SELECT count(*) FROM knowledge_units u WHERE u.content_id=c.id AND u.kind='method' AND {ACTIVE_RUN}) AS n_methods, "
                f"(SELECT count(*) FROM knowledge_units u WHERE u.content_id=c.id AND u.kind='concept' AND {ACTIVE_RUN}) AS n_concepts, "
                f"(SELECT count(*) FROM claim_scores s JOIN knowledge_units u ON u.id=s.unit_id "
                f" WHERE u.content_id=c.id AND s.outcome='hit' AND {ACTIVE_RUN}) AS n_hit, "
                f"(SELECT count(*) FROM claim_scores s JOIN knowledge_units u ON u.id=s.unit_id "
                f" WHERE u.content_id=c.id AND s.outcome='partial' AND {ACTIVE_RUN}) AS n_partial, "
                f"(SELECT count(*) FROM claim_scores s JOIN knowledge_units u ON u.id=s.unit_id "
                f" WHERE u.content_id=c.id AND s.outcome='miss' AND {ACTIVE_RUN}) AS n_miss "
                f"FROM contents c JOIN creators cr ON cr.id=c.creator_id {cond} "
                f"ORDER BY c.published_at DESC NULLS LAST, c.id DESC LIMIT %s", params,
            ).fetchall()

    # --- 关键帧（视觉笔记的像素凭据）-----------------------------------------

    def record_keyframe(self, content_id: int, *, ts_s: int, path: str, height: int,
                        bytes_: int, source: str, kind: str | None = None,
                        note: str | None = None) -> None:
        """(content, ts) 唯一；重抓（如提高清晰度）覆盖同一行。"""
        with self.pool.connection() as conn:
            conn.execute(
                "INSERT INTO keyframes(content_id, ts_s, kind, note, path, height, bytes, source) "
                "VALUES (%s,%s,%s,%s,%s,%s,%s,%s) "
                "ON CONFLICT (content_id, ts_s) DO UPDATE SET "
                "path=EXCLUDED.path, height=EXCLUDED.height, bytes=EXCLUDED.bytes, "
                "source=EXCLUDED.source, kind=COALESCE(EXCLUDED.kind, keyframes.kind), "
                "note=COALESCE(EXCLUDED.note, keyframes.note)",
                (content_id, ts_s, kind, note, path, height, bytes_, source))

    def keyframes_for_content(self, content_id: int) -> list[dict]:
        with self.pool.connection() as conn:
            return conn.execute(
                "SELECT * FROM keyframes WHERE content_id=%s ORDER BY ts_s", (content_id,),
            ).fetchall()

    def known_tags(self) -> set[str]:
        """生效版本里已经用过的全部标签——import 时的词表体检拿它当受控词表。

        用库而不是在代码里再写一份主题词表：extraction-guide §7 本身就是那份表，
        复制一遍必然漂移；而"这个词以前用过没有"恰好就是要问的问题。
        """
        with self.pool.connection() as conn:
            rows = conn.execute(
                f"SELECT DISTINCT unnest(u.tags) AS tag FROM knowledge_units u "
                f"WHERE {ACTIVE_RUN}").fetchall()
        return {r["tag"] for r in rows}

    def keyframe_seconds(self, content_id: int) -> set[int]:
        """已有帧的时间戳集合（回填幂等用）。"""
        with self.pool.connection() as conn:
            rows = conn.execute("SELECT ts_s FROM keyframes WHERE content_id=%s",
                                (content_id,)).fetchall()
        return {int(r["ts_s"]) for r in rows}

    def freeze_ref_price(self, unit_id: int, ref: float) -> bool:
        """把回查到的发布日参考价固化到单元上（只在还空着时写，绝不覆盖已有值）。

        ref_price_at_publish 是 PIT 锚点。提取时拿不到屏价就会空着，评分器只好回查
        发布日收盘——但 yfinance 给的是复权价，标的一拆股历史行情整体改写，同一条 claim
        的 +7/+30/+90 三个时点就会各自对着不同的参考价。第一次查到就钉死，之后不再漂。
        """
        with self.pool.connection() as conn:
            r = conn.execute(
                "UPDATE knowledge_units SET ref_price_at_publish=%s "
                "WHERE id=%s AND ref_price_at_publish IS NULL", (ref, unit_id))
        return r.rowcount > 0

    def activate_run(self, run_id: int) -> dict:
        """把某个 run 设为该 content 当前生效的那一版（其余转 superseded）。

        用于回退：v2 重提之后发现不如 v1，activate v1 的 run 即可，两版单元都还在库里。
        """
        with self.pool.connection() as conn:
            row = conn.execute("SELECT content_id, extractor_version FROM extraction_runs "
                               "WHERE id=%s", (run_id,)).fetchone()
            if row is None:
                raise ValueError(f"run {run_id} 不存在")
            conn.execute("UPDATE extraction_runs SET status='superseded' "
                         "WHERE content_id=%s AND id<>%s", (row["content_id"], run_id))
            conn.execute("UPDATE extraction_runs SET status='active' WHERE id=%s", (run_id,))
        return {"run_id": run_id, "content_id": row["content_id"],
                "extractor_version": row["extractor_version"]}

    def runs_for_content(self, content_id: int) -> list[dict]:
        """某内容的全部提取版本（含已被取代的），看得到才谈得上切换。"""
        with self.pool.connection() as conn:
            return conn.execute(
                "SELECT id, extractor_version, model, n_units, status, created_at "
                "FROM extraction_runs WHERE content_id=%s ORDER BY created_at",
                (content_id,)).fetchall()

    def keyframe(self, keyframe_id: int) -> dict | None:
        """按 id 取单帧（读图端点用 id 而不是路径——路径来自库里，不给穿越的口子）。"""
        with self.pool.connection() as conn:
            return conn.execute("SELECT * FROM keyframes WHERE id=%s", (keyframe_id,)).fetchone()

    def keyframes_near(self, content_id: int, ts_s: int, *, window_s: int) -> list[dict]:
        """某内容里落在 [ts-window, ts+window] 的帧，按与 ts 的距离排序。"""
        with self.pool.connection() as conn:
            return conn.execute(
                "SELECT *, abs(ts_s - %s) AS distance_s FROM keyframes "
                "WHERE content_id=%s AND ts_s BETWEEN %s AND %s ORDER BY distance_s, ts_s",
                (ts_s, content_id, ts_s - window_s, ts_s + window_s)).fetchall()

    def keyframe_span(self, content_id: int) -> tuple[int, int] | None:
        """该内容已有帧的时间跨度（判断 locator 是否越界用）。"""
        with self.pool.connection() as conn:
            row = conn.execute(
                "SELECT min(ts_s) AS lo, max(ts_s) AS hi FROM keyframes WHERE content_id=%s",
                (content_id,)).fetchone()
        return (int(row["lo"]), int(row["hi"])) if row and row["lo"] is not None else None

    # --- L1 提取（版本化重放）----------------------------------------------

    def record_extraction(self, content_id: int, *, extractor_version: str,
                          model: str | None, units: list[KnowledgeUnit],
                          ref_prices: dict[int, float] | None = None) -> list[int]:
        """一次提取运行：runs 上 (content_id, version) 唯一；重复运行报错（换版本号重跑）。
        ref_prices: 单元下标 → 发布时刻市价（claim 用）。返回 unit id 列表。

        新 run 落库即接管 active，同一条 content 的旧 run 转 superseded（旧单元一条不删，
        只是不再进下游统计）。整件事在一个事务里：不允许出现"两版都 active"的中间态，
        部分唯一索引也会拦。要回退到旧版走 activate_run。
        """
        c = self.get_content(content_id)
        if c is None:
            raise ValueError(f"content {content_id} 不存在")
        ids: list[int] = []
        with self.pool.connection() as conn:
            conn.execute("UPDATE extraction_runs SET status='superseded' "
                         "WHERE content_id=%s AND status='active'", (content_id,))
            run = conn.execute(
                "INSERT INTO extraction_runs(content_id, extractor_version, model, n_units) "
                "VALUES (%s,%s,%s,%s) RETURNING id",
                (content_id, extractor_version, model, len(units)),
            ).fetchone()
            for i, u in enumerate(units):
                row = conn.execute(
                    "INSERT INTO knowledge_units(run_id, content_id, creator_id, published_at, "
                    "kind, quote, locator, extractor_version, model, payload, tags, "
                    "ref_price_at_publish) VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s) "
                    "RETURNING id",
                    (run["id"], content_id, c["creator_id"], c["published_at"], u.kind,
                     u.quote, u.locator, extractor_version, model, Json(u.payload), u.tags,
                     (ref_prices or {}).get(i)),
                ).fetchone()
                ids.append(int(row["id"]))
            conn.execute("UPDATE contents SET status='extracted' WHERE id=%s", (content_id,))
        return ids

